// Writes the date each docs page last changed, from git history, to a
// generated module the app imports. Runs before every build and serve.
// Without git history (a shallow clone or a tarball) the dates are left out
// and pages simply show no "Last updated" line.
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src/content');
const outFile = join(contentDir, 'last-updated.generated.ts');

const dates = {};
for (const section of readdirSync(contentDir, { withFileTypes: true })) {
  if (!section.isDirectory()) continue;
  for (const file of readdirSync(join(contentDir, section.name))) {
    if (!file.endsWith('.md')) continue;
    const path = join(contentDir, section.name, file);
    let date = '';
    try {
      date = execFileSync('git', ['log', '-1', '--format=%cI', '--', path], {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
    } catch {
      // No git, or not a repository: leave the date out.
    }
    if (date) {
      dates[relative(contentDir, path).replace(/\\/g, '/')] = date;
    }
  }
}

writeFileSync(
  outFile,
  `// Generated by scripts/content-dates.mjs. Do not edit.\n` +
    `/** Last commit date per content file, keyed by path below src/content. */\n` +
    `export const LAST_UPDATED: Record<string, string> = ${JSON.stringify(dates, null, 2)};\n`,
);
console.log(`Wrote ${Object.keys(dates).length} dates to ${relative(root, outFile)}`);
